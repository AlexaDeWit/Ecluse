-- | The restored positive control must pass after the semantic mutations.
controls :: FilePath -> IO ()
controls seedEvidence = do
    createDirectoryIfMissing True "scratchpad"
    withTempDirectory "scratchpad" "residency-evidence-controls" $ \temporaryRoot -> do
        absoluteRoot <- makeAbsolute temporaryRoot
        let root = absoluteRoot </> "evidence"
            sentinel = absoluteRoot </> "sentinel"
        writeComparisonText sentinel "contained sentinel\n"
        metricControls
        prepareFixture seedEvidence root
        preparationFaults root >>= requireAccepted "complete preparation fixture"
        auditFaults root "run-7" "2" >>= requireAccepted "complete residency fixture"
        let firstProbe = fromMaybe (Probe "invalid" "" "" "") (listToMaybe merges)
            generated = generationDirectory "A1" firstProbe
            child = childDirectory "A1" firstProbe
            change path = writeComparisonText (root </> path)
            manifest transform = do
                records <- readJsonFile (root </> generated </> "manifest.json")
                writeJsonFile (root </> generated </> "manifest.json") (transform (records :: [Generated]))
            mutations =
                [ ("changed generated bytes", "generated input bytes differ", change (generated </> "private.json") "changed")
                , ("substituted generated bytes", "generated input bytes differ", copyFile (root </> generated </> "public.original") (root </> generated </> "private.json"))
                , ("missing generated bytes", "missing bound artifact", removeFile (root </> generated </> "private.json"))
                , ("duplicate generated record", "duplicate", manifest (\records -> records <> take 1 records))
                , ("wrong shape", "generated shape or package differs", manifest (map (\record -> record{generatedShape = "Identical"})))
                , ("wrong package", "generated shape or package differs", manifest (map (\record -> record{generatedPackage = "webpack"})))
                , ("wrong helper source", "generated helper source differs", manifest (map (\record -> record{generatedSource = sourceFor "B"})))
                , ("wrong helper identity", "generated helper source differs", manifest (map (\record -> record{generatedHelper = "wrong"})))
                , ("wrong archive", "generated path or archive differs", manifest (map (\record -> record{generatedArchive = "substituted.json"})))
                , ("wrong original path", "generated path or archive differs", manifest (map (\record -> record{generatedOriginal = "/substituted.json"})))
                ,
                    ( "refreshed generated manifest"
                    , "generated input bytes differ"
                    , do
                        change (generated </> "private.json") "changed"
                        manifest (map (\record -> if generatedRole record == "private" then record{generatedSha256 = digest "changed", generatedBytes = 7} else record))
                    )
                ,
                    ( "substituted helper with identical inputs"
                    , "helper changed during generation"
                    , do
                        hashes <- checksums (root </> generated </> "helper-before.sha256")
                        change (generated </> "helper-before.sha256") (T.unlines [T.replicate 64 "0" <> "  " <> toText path | path <- Map.keys hashes])
                    )
                , ("corpus traversal sentinel", "native corpus inventory differs", change "build-A/corpus.sha256" (digest "contained sentinel\n" <> "  ../../sentinel\n"))
                , ("lock traversal sentinel", "dependency lock path escapes archive", change "build-A/locks.sha256" (digest "contained sentinel\n" <> "  ../../../sentinel\n"))
                , ("absolute lock sentinel", "dependency lock path escapes archive", change "build-A/locks.sha256" (digest "contained sentinel\n" <> "  " <> toText sentinel <> "\n"))
                , ("source archive substitution", "exact source archive differs", change "source-A.tar" "substituted snapshot")
                , ("configuration substitution", "exact source configuration differs", forM_ ["build-A/config/ecluse.cabal", "helper-build-A/config/ecluse.cabal", "source-configs-A/ecluse.cabal"] (`change` "substituted config"))
                , ("helper plan substitution", "residency plan source path differs", alterPlan root "helper-build-A/plan.json" "ecluse" "pkg-src" (toJSON (Map.fromList [("type", "local"), ("path", "/substituted")] :: Map Text Text)))
                , ("native plan substitution", "residency plan flags differ", alterPlan root "build-A/plan.json" "ecluse" "flags" (toJSON (Map.singleton ("dev-http-egress" :: Text) False)))
                , ("external dependency substitution", "external dependency plan differs", alterPlan root "helper-build-A/plan.json" "base" "pkg-version" (toJSON ("9.9.9" :: Text)))
                , ("toolchain substitution", "identified toolchain differs", forM_ ["build-A/toolchain.txt", "helper-build-A/toolchain.txt"] (`change` "substituted compiler\n"))
                , ("missing mandatory inventory", "missing bound artifact", removeFile (root </> "overlay/controller-task.yml"))
                , ("missing observation", "native child must contain exactly one observation", change (child </> "native.json") "")
                ,
                    ( "duplicate observation"
                    , "native child must contain exactly one observation"
                    , do
                        bytes <- readFileBS (root </> child </> "native.json")
                        writeFileBS (root </> child </> "native.json") (bytes <> bytes)
                    )
                , ("failed helper", "recorded command failed", change (generated </> "status") "7\n")
                , ("helper command", "helper command differs", change (generated </> "command.txt") "wrong\n")
                , ("helper overlay", "helper overlay differs", change "helper-build-A/overlay.patch" "diff --git a/test/residency/Main.hs b/test/residency/Main.hs\nwrong\n")
                , ("native command", "native command differs", change (child </> "command.txt") "wrong\n")
                , ("native status", "recorded command failed", change (child </> "native.status") "7\n")
                , ("native binary", "recorded executable path or digest differs", change "build-A/ecluse-residency" "wrong")
                , ("native source", "native or helper source differs", change "build-A/source.txt" (T.unlines [sourceFor "B", treeFor "B"]))
                , ("native snapshot", "recorded snapshot differs", change (child </> "after/source.txt") "wrong\n")
                , ("live inputs", "live native input hashes differ", change (child </> "inputs-after.sha256") (T.replicate 64 "0" <> "  substituted\n"))
                , ("overlapping times", "serial pass order differs", change "order.txt" "0000 start child A1-s3-heavy\n")
                , ("wrong run", "run identity differs", alterMap root "run.json" "run" "other")
                , ("wrong attempt", "run identity differs", alterMap root "run.json" "attempt" "other")
                , ("wrong worker", "worker identity differs", change "worker.txt" "run=run-7\nattempt=2\nrunner=other\nimage=fixture\naarch64\n")
                ,
                    ( "missing child field"
                    , "key"
                    , do
                        Object record <- readJsonFile (root </> child </> "native.json")
                        writeJsonFile (root </> child </> "native.json") (Object (KeyMap.delete "listingPeak" record))
                    )
                ]
        paths <- inventory root
        originals <- traverse (\path -> (path,) <$> readFileBS (root </> path)) paths
        let restore = do
                forM_ originals (\(path, bytes) -> writeFileBS (root </> path) bytes)
                refresh root paths
                auditFaults root "run-7" "2" >>= requireAccepted "restored complete fixture"
        forM_ mutations $ \(label, expectedFault, mutate) -> flip finally restore $ do
            mutate
            refresh root paths
            faults <- auditFaults root "run-7" "2"
            requireRejected label faults
            when (label == "substituted helper with identical inputs") $ do
                prepared <- preparationFaults root
                requireRejected "substituted helper preflight" prepared
                requireDiagnostic (any (T.isInfixOf "helper changed during generation") prepared) "helper substitution reached the wrong preflight refusal"
                forM_ ["private.original", "public.original"] $ \file -> do
                    let path = generated </> file
                    bytes <- readFileBS (root </> path)
                    requireDiagnostic (List.lookup path originals == Just bytes) "substitution control changed generated bytes"
            unless (T.null expectedFault || any (T.isInfixOf expectedFault) faults) (fail (toString (label <> " failed for an unrelated reason: " <> T.unlines faults)))
        auditFaults root "other-run" "2" >>= requireRejected "external run identity"
        auditFaults root "run-7" "other-attempt" >>= requireRejected "external attempt identity"
        auditFaults root "run-7" "2" >>= requireAccepted "restored complete fixture"
        audit root "run-7" "2"
        compared <- T.lines <$> readComparisonText (root </> "comparison.tsv")
        requireDiagnostic (length compared == 1 + 3 * 6 * 7) "six-pair metric coverage differs"
        putTextLn "Complete residency evidence controls passed."

refresh :: FilePath -> [FilePath] -> IO ()
refresh root paths = do
    forM_ schedule $ \(name, probe) -> writeConditions root name (probeId probe)
    existing <- filterM (doesFileExist . (root </>)) paths
    context <- readJsonFile (root </> "run.json")
    artifacts <- Map.fromList <$> traverse (\path -> (path,) <$> digestFile (root </> path)) existing
    writeJsonFile (root </> "binding.json") (Binding 1 context artifacts)

alterMap :: FilePath -> FilePath -> Text -> Text -> IO ()
alterMap root path key value = do
    values <- readJsonFile (root </> path)
    writeJsonFile (root </> path) (Map.insert key value (values :: Map Text Text))

alterPlan :: FilePath -> FilePath -> Text -> Text -> Value -> IO ()
alterPlan root path package field replacement = do
    plan <- readJsonFile (root </> path)
    units <- either fail pure (planUnits plan)
    let change (Object unit) | KeyMap.lookup "pkg-name" unit == Just (toJSON package) = Object (KeyMap.insert (fromString (toString field)) replacement unit)
        change unit = unit
    case plan of
        Object fields -> writeJsonFile (root </> path) (Object (KeyMap.insert "install-plan" (toJSON (map change units)) fields))
        _ -> fail "plan mutation needs an object"
